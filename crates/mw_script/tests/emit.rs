//! Emitter fixtures (our own scripts, never vanilla text): a golden module, numeric semantics,
//! dialogue results, inert stubs, missing arguments; every module is loaded and run once in a
//! real sandboxed `sf_script` context with the `mw` runtime skeleton.

// Conversions are exact by design (wrap, truncation, f32 rounding): compare bit-for-bit.
#![allow(clippy::float_cmp)]

mod support;

use mw_script::emit::{field, lua_string};
use mw_script::{FunctionTable, NoEnv, SourceKind, emit_dialogue, emit_script, parse_and_resolve};
use support::Harness;

fn script(id: &str, text: &str) -> String {
    let table = FunctionTable::vanilla();
    let parsed = parse_and_resolve(text, SourceKind::Script, table, &NoEnv);
    emit_script(id, "fixture.esp", &parsed, table, &NoEnv)
}

const GOLDEN_SRC: &str = r#"Begin w2_golden
short n
float t
if ( MenuMode == 1 )
  return
endif
set t to t + GetSecondsPassed
if ( OnActivate )
  "w2_gate"->Disable
  set n to n + 1
  MessageBox "Count %g" n "Ok"
endif
End
"#;

const GOLDEN_LUAU: &str = r#"-- generated by mw_script v1 from SCPT "W2_Golden" (fixture.esp), do not edit
return function(mw)
local G, ref = mw.globals, mw.ref
local short, long, float = mw.short, mw.long, mw.float
return mw.script({
  id = "w2_golden",
  vars = { n = "short", t = "float", },
  activation = "script",
  tick = function(self, v)
    if mw.menu_mode(self) == 1 then -- L4
      do return end -- L5
    end -- L4
    v.t = float((v.t + mw.get_seconds_passed(self))) -- L7
    if self:on_activate() ~= 0 then -- L8
      ref("w2_gate"):disable() -- L9
      v.n = short((v.n + 1)) -- L10
      mw.message_box(self, "Count %g", v.n, "Ok") -- L11
    end -- L8
  end,
})
end
"#;

#[test]
fn golden_module() {
    let out = script("W2_Golden", GOLDEN_SRC);
    assert_eq!(out, GOLDEN_LUAU, "\n{out}");
    let mut h = Harness::new(FunctionTable::vanilla());
    let o = h.run_module("w2_golden", &out);
    assert!(o.ran, "{o:?}");
    assert_eq!(h.field::<String>("def:w2_golden", "activation"), "script");
    // No host: MenuMode, OnActivate, GetSecondsPassed answered their neutral 0.
    let calls = h.fallback_calls();
    assert!(calls.contains(&("menu_mode".to_owned(), 1)), "{calls:?}");
    assert!(calls.contains(&("on_activate".to_owned(), 1)), "{calls:?}");
}

#[test]
fn numeric_semantics() {
    let src = "Begin w2_numbers
short s
long l
float f
short q
float h
short n
short z
set s to 32767 + 2
set l to 2147483647 + 1
set f to 0.1
set q to 7 / 2
set h to 7 / 2
set n to -7 / 2
set z to 1 / 0
End";
    let out = script("w2_numbers", src);
    let mut h = Harness::new(FunctionTable::vanilla());
    assert!(h.run_module("w2_numbers", &out).ran, "{out}");
    let var = |h: &mut Harness, n: &str| h.field::<f64>("vars:w2_numbers", n);
    assert_eq!(var(&mut h, "s"), -32767.0, "short wraps");
    assert_eq!(var(&mut h, "l"), -2_147_483_648.0, "long wraps");
    assert_eq!(var(&mut h, "f"), f64::from(0.1_f32), "float rounds through f32");
    assert_eq!(var(&mut h, "q"), 3.0, "integer / integer: float division, truncated on assignment");
    assert_eq!(var(&mut h, "h"), 3.5);
    assert_eq!(var(&mut h, "n"), -3.0, "truncation toward zero");
    assert_eq!(var(&mut h, "z"), 0.0, "non-finite becomes 0");
}

#[test]
fn dialogue_results_and_inert_scripts() {
    let table = FunctionTable::vanilla();
    let a = parse_and_resolve(
        "Journal \"w2_quest\" 10\nset w2_mood to w2_mood + 2\nAddItem \"gold_001\"\nGoodbye",
        SourceKind::DialogueResult,
        table,
        &NoEnv,
    );
    let b = parse_and_resolve("player->AddItem w2_ring 1", SourceKind::DialogueResult, table, &NoEnv);
    let out = emit_dialogue("W2 Topic", "fixture.esp", &[("1", &a), ("2", &b)], table, &NoEnv);
    assert!(out.contains("mw.set_var(self, \"w2_mood\", (mw.get_var(self, \"w2_mood\") + 2))"), "{out}");
    assert!(out.contains("self:add_item(\"gold_001\", 0)"), "missing count reads 0:\n{out}");
    assert!(out.contains("ref(\"player\"):add_item(\"w2_ring\", 1)"), "{out}");
    let mut h = Harness::new(table);
    assert!(h.run_module("topic", &out).ran, "{out}");
    let calls = h.fallback_calls();
    assert!(calls.contains(&("journal".to_owned(), 1)), "{calls:?}");
    assert!(calls.contains(&("goodbye".to_owned(), 1)), "{calls:?}");

    // An unknown function at a statement head: inert, never runs, keeps its variables.
    let inert = script("w2_inert", "Begin w2_inert\nshort x\nxGetMWSEThing 3\nset x to 1\nEnd");
    assert!(inert.contains("inert = "), "{inert}");
    assert!(!inert.contains("set_var") && !inert.contains("v.x ="), "{inert}");
    assert!(h.run_module("w2_inert", &inert).ran);
    assert_eq!(h.field::<f64>("vars:w2_inert", "x"), 0.0);
}

#[test]
fn names_and_strings() {
    assert_eq!(field("v", "timer"), "v.timer");
    assert_eq!(field("v", "end"), "v[\"end\"]");
    assert_eq!(field("v", "a-b"), "v[\"a-b\"]");
    assert_eq!(field("v", "1st"), "v[\"1st\"]");
    assert_eq!(lua_string("a \"q\" \\ \n\u{1}"), "\"a \\\"q\\\" \\\\ \\n\\001\"");
}

#[test]
fn oracle_flags_count_integer_division_and_mixed_comparisons() {
    let table = FunctionTable::vanilla();
    let p = parse_and_resolve(
        "Begin w2_oracle
short a
short b
float f
set a to a / 2
set f to f / 2
set b to ( a / b ) / 2
if ( a < f )
  set b to 1
elseif ( a == 2 )
  set b to 2
endif
if ( f > 3 )
  set b to 3
endif
End",
        SourceKind::Script,
        table,
        &NoEnv,
    );
    let flags = mw_script::oracle_flags(&p, table, &NoEnv);
    // `a / 2`, `a / b`; `(a / b) / 2` has an operand of unknown kind; `f / 2` is float;
    // `a < f` counts, `f > 3` (a literal) does not.
    assert_eq!(flags.int_div, 2, "{flags:?}");
    assert_eq!(flags.mixed_cmp, 1, "{flags:?}");
}
