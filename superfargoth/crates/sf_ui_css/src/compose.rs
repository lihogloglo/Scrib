//! The stylesheet composer (ui.md "Data model and moddability"): one generated root sheet that
//! imports every source sheet into its own cascade layer, so later layers win the way later mods
//! win in load order, and nothing escapes into the unlayered (strongest) cascade.
//!
//! Plain text in, plain text out: no Bevy, no flair types.

use std::fmt::Write as _;

/// Which group of cascade layers a sheet belongs to. Declared in this order; later wins.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum LayerKind {
    /// The framework's base sheets (layer `sf`).
    Framework,
    /// The active layout preset (layer `preset`).
    Preset,
    /// The active theme and its enabled accessibility variants (layer `theme`).
    Theme,
    /// One layer per mod, in load order (`mods-<position>-<id>`).
    Mod,
    /// The player's own overrides, last (layer `user`).
    User,
}

/// One imported sheet and who answers for it.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SheetSource {
    pub kind: LayerKind,
    /// The cascade layer it is imported into.
    pub layer: String,
    /// The mod that ships it: the mod itself for [`LayerKind::Mod`], the owner of the theme or
    /// preset record for those, `None` for framework and user sheets.
    pub mod_id: Option<String>,
    /// VFS path.
    pub path: String,
}

/// Inputs of one composition. Order inside each group is kept (mods: load order).
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Composition {
    framework: Vec<String>,
    preset: Vec<(Option<String>, String)>,
    theme: Vec<(Option<String>, String)>,
    mods: Vec<(String, String)>,
    user: Vec<String>,
}

impl Composition {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn framework(&mut self, path: impl Into<String>) -> &mut Self {
        self.framework.push(path.into());
        self
    }

    pub fn preset(&mut self, owner: Option<&str>, path: impl Into<String>) -> &mut Self {
        self.preset.push((owner.map(str::to_owned), path.into()));
        self
    }

    pub fn theme(&mut self, owner: Option<&str>, path: impl Into<String>) -> &mut Self {
        self.theme.push((owner.map(str::to_owned), path.into()));
        self
    }

    /// A mod's stylesheet. Call in load order; a mod's sheets share its layer, in call order.
    pub fn mod_sheet(&mut self, mod_id: impl Into<String>, path: impl Into<String>) -> &mut Self {
        self.mods.push((mod_id.into(), path.into()));
        self
    }

    pub fn user(&mut self, path: impl Into<String>) -> &mut Self {
        self.user.push(path.into());
        self
    }

    /// The root sheet. `source` names the asset source the paths are imported from (an import
    /// resolves against the root sheet's own source unless it names one).
    pub fn compose(&self, source: &str) -> ComposedSheet {
        let mut sheets = Vec::new();
        let mut layers = vec!["sf".to_owned(), "preset".to_owned(), "theme".to_owned()];
        for path in &self.framework {
            sheets.push(SheetSource {
                kind: LayerKind::Framework,
                layer: "sf".into(),
                mod_id: None,
                path: path.clone(),
            });
        }
        for (owner, path) in &self.preset {
            sheets.push(SheetSource {
                kind: LayerKind::Preset,
                layer: "preset".into(),
                mod_id: owner.clone(),
                path: path.clone(),
            });
        }
        for (owner, path) in &self.theme {
            sheets.push(SheetSource {
                kind: LayerKind::Theme,
                layer: "theme".into(),
                mod_id: owner.clone(),
                path: path.clone(),
            });
        }
        let mut mod_layers: Vec<(&str, String)> = Vec::new();
        for (id, path) in &self.mods {
            let layer = if let Some((_, layer)) = mod_layers.iter().find(|(m, _)| *m == id.as_str())
            {
                layer.clone()
            } else {
                let layer = mod_layer_name(mod_layers.len() + 1, id);
                mod_layers.push((id, layer.clone()));
                layers.push(layer.clone());
                layer
            };
            sheets.push(SheetSource {
                kind: LayerKind::Mod,
                layer,
                mod_id: Some(id.clone()),
                path: path.clone(),
            });
        }
        layers.push("user".into());
        for path in &self.user {
            sheets.push(SheetSource {
                kind: LayerKind::User,
                layer: "user".into(),
                mod_id: None,
                path: path.clone(),
            });
        }

        let mut css = String::from(
            "/* Generated by sf_ui_css (ui.md): one cascade layer per source, later layers win; mods in load order. */\n",
        );
        let _ = writeln!(css, "@layer {};", layers.join(", "));
        for sheet in &sheets {
            let _ = writeln!(
                css,
                "@import url(\"{}\") layer({});",
                css_string(&asset_url(source, &sheet.path)),
                sheet.layer
            );
        }
        ComposedSheet {
            css,
            layers,
            sheets,
        }
    }
}

/// A generated root sheet and how its layers map back to sources.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct ComposedSheet {
    pub css: String,
    /// Layer names in declaration order (weakest first).
    pub layers: Vec<String>,
    /// Imports in the order they appear.
    pub sheets: Vec<SheetSource>,
}

impl ComposedSheet {
    /// Who answers for the sheet at `path` (a VFS path, as given to the [`Composition`]).
    pub fn sheet(&self, path: &str) -> Option<&SheetSource> {
        self.sheets.iter().find(|s| s.path == path)
    }

    /// The layer a mod's sheets go to.
    pub fn mod_layer(&self, mod_id: &str) -> Option<&str> {
        self.sheets
            .iter()
            .find(|s| s.kind == LayerKind::Mod && s.mod_id.as_deref() == Some(mod_id))
            .map(|s| s.layer.as_str())
    }
}

/// `mods-<position>-<id>`. `bevy_flair` 0.9 takes one CSS identifier per layer name (no dotted
/// `mods.<id>` sub-layers), and mod ids may contain `.`, so the id is reduced to identifier
/// characters; the load position keeps names unique.
pub fn mod_layer_name(position: usize, mod_id: &str) -> String {
    let id: String = mod_id
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                c.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect();
    format!("mods-{position}-{id}")
}

/// `source://path` (no source for an empty name).
pub fn asset_url(source: &str, path: &str) -> String {
    if source.is_empty() {
        path.to_owned()
    } else {
        format!("{source}://{path}")
    }
}

fn css_string(raw: &str) -> String {
    raw.replace('\\', "\\\\").replace('"', "\\\"")
}
