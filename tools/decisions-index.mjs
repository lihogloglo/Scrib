#!/usr/bin/env node
// decisions-index.mjs: generates superfargoth/docs/DECISIONS-INDEX.md from superfargoth/docs/DECISIONS.md
// (doc audit 2026-10-25, slice S9a). Node, no dependencies. Run from anywhere: node tools/decisions-index.mjs
// Deterministic: same input, same output (no timestamps).

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Tag -> pattern, matched case-insensitively on the whole entry text (bullet line + its continuation lines).
// Extend here: add a row; an entry may carry several tags; untagged entries get "-".
const TAGS = [
  ["shadows", /shadow/],
  ["lights", /\blights?\b|\blamps?\b|lights\.md|light budget/],
  ["weather", /weather|\brain|\bfog\b|cloud|\bwind\b|sf_wind|\bhaze|\bsnow|\bstorm/],
  ["sky", /\bsky\b|sf_sky|atmos|\bsun\b|\bmoons?\b|exposure|ev100|night/],
  ["water", /water|\bswell|\bshore|\bocean|\bwaves?\b/],
  ["terrain", /terrain|clipmap|heightmap|\bland\b/],
  ["lod", /\bh?lods?\b|far[- ]field|impostor|far proxy|sizecull|size-based cull|meshopt|\bvat\b|open_vat/],
  ["anim", /\banim|\bclips?\b|ragdoll|\bfoot|\bfeet\b|locomotion|skeleton|root[- ]motion|\bgait|\bkf\b|\bbvh\b/],
  ["physics", /\bphysics\b|rapier|collider|collision|ragdoll|\bcloth\b|\bcarry\b|impulse joint/],
  ["character", /character|smooth ?bod|outfit|held item|\bactors?\b|\bnpcs?\b|body part|\bmorph|\bskin/],
  ["controller", /controller|\bmover\b|kinematic|\bjumps?\b|locomotion::launch|\bwalkers?\b/],
  ["camera", /camera/],
  ["ui", /\bui\b|sf_ui|ui\.md|\bhud\b|\bmenus?\b|bevy_flair|\bcss\b|enhanced_input|\bfonts?\b|\bbindings?\b/],
  ["save", /\bsav(e|es|ed|ing)\b|sf_save|saves2|reload_resident/],
  ["mods", /\bmods?\b|sf_mods|mod set|load order|\.esp\b|\besps?\b|content packs?|hot reload|\bvfs\b|\bbsas?\b/],
  ["records", /\brecords?\b|mw_records|\besms?\b|\.esm\b|\btes3\b/],
  ["bake", /\bbak(e|ed|es|ing)\b|sf_bake|bake\.md|\bcook(?!ies)/],
  ["nif", /\bnifs?\b|mw_nif|nif-runtime/],
  ["scripting", /script|\bluau?\b|mudcrab/],
  ["console", /console/],
  ["audio", /audio|\bsounds?\b|\bmusic|rodio|ambience/],
  ["rpg", /\brpg\b|dialogue|journal|\bquests?\b|\bmagic|\bspells?\b|\bstats\b|sf_rpg|mw_rpg|\binfo\b/],
  ["net", /\bnet\b|net\.md|co-op|\bcoop|multiplayer|replicat|playerid|max_players/],
  ["dlss", /dlss|\btaa\b|upscal|temporal resolve/],
  ["perf", /\bperf\b|perf\.md|performance|\d ?ms\b|frame (time|target|pacing)|\bfps\b|budget|optimi[sz]|occlusion cull|culling/],
  ["build", /cargo|compile|\bbuild (perf|setup|time)|workspace|crate convention|hakari|toolchain|vendored/],
  ["license", /licen[cs]|\bgpl|\bmit\b|apache|\bmpl|provenance|copyright/],
  ["docs", /docs only|doc diet|documentation|doc (cleanup|audit|budget)|claude\.md|decisions\.md/],
  ["process", /orchestrator|\bsessions?\b|milestones?|\bphases\b|\bphase ?[0-9]|workflow|\bagents?\b|roadmap|priorit/],
];

const EXCERPT = 55; // chars of entry text per index line; keep the index <= ~20 KB

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "superfargoth/docs/DECISIONS.md");
const OUT = join(root, "superfargoth/docs/DECISIONS-INDEX.md");

const lines = readFileSync(SRC, "utf8").replace(/\r\n?/g, "\n").split("\n");

// An entry = a top-level bullet ("- ...") plus following blank or indented lines.
const entries = [];
for (let i = 0; i < lines.length; i++) {
  if (!lines[i].startsWith("- ")) continue;
  let j = i + 1;
  while (j < lines.length && (lines[j] === "" || /^\s/.test(lines[j]))) j++;
  entries.push({ line: i + 1, text: lines.slice(i, j).join("\n") });
  i = j - 1;
}

const plain = (s) =>
  s
    .replace(/\*\*|__|`|~~/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/\s+/g, " ")
    .replace(/\|/g, "/")
    .trim();

const out = [];
for (const { line, text } of entries) {
  let body = plain(text.slice(2)); // drop "- "
  const m = body.match(/^(\d{4}-\d{2}-\d{2})/);
  const date = m ? m[1] : "-";
  if (m) {
    body = body.slice(m[1].length);
    // "(slug; spec refs...)" -> "(slug)": spec refs are in the entry itself, the slug is enough here
    body = body.replace(/^,?\s*\(([^;)]*)[^)]*\)/, "($1)").replace(/^[\s,:.]+/, "");
    body = body.replace(/^(\([^)]*\))[\s:.,]+/, "$1 ");
  }
  const lc = text.toLowerCase();
  const tags = TAGS.filter(([, re]) => re.test(lc)).map(([t]) => t);
  const excerpt = body.length > EXCERPT ? body.slice(0, EXCERPT).trimEnd() + "..." : body;
  out.push(`L${line} | ${date} | ${tags.join(",") || "-"} | ${excerpt}`);
}

const header = [
  "# DECISIONS.md index (generated)",
  "",
  "Generated by `node tools/decisions-index.mjs` from `DECISIONS.md`: **don't edit**, re-run after appending.",
  "Use: grep this file for a tag or word (`grep -n \"physics\" superfargoth/docs/DECISIONS-INDEX.md`), then read",
  "the entry at its line: `sed -n '<line>,+12p' superfargoth/docs/DECISIONS.md`.",
  `Format: \`L<line> | <date> | <tags> | <first ~${EXCERPT} chars>\`. Tags (keyword match, see the script):`,
  TAGS.map(([t]) => t).join(", ") + ".",
  "Entries from line 789 on sit physically under \"## 11. Open decisions\" (later decisions were appended there);",
  "the two undated ones are the open decisions.",
  "",
];
writeFileSync(OUT, header.concat(out).join("\n") + "\n", "utf8");
console.log(`decisions-index: ${entries.length} entries -> ${OUT} (${Buffer.byteLength(header.concat(out).join("\n") + "\n")} bytes)`);
